export interface DraftedQuestion {
  section: CloserKey;
  question: string;
}

interface Drafted {
  questions: DraftedQuestion[];
}

const SECTION_KEYS = new Set<string>(CLOSER_SECTIONS.map((s) => s.key));

function wordCount(s: string): number {
  return s.trim().split(/\s+/).filter(Boolean).length;
}

/**
 * Every rule the questions have to satisfy, as data, so validate() and describeInvalid() cannot
 * disagree about what failed.
 *
 * ‼️ describeInvalid MUST COVER THE WHOLE VALIDATOR, AND booking-script.ts RECORDS WHAT HAPPENS
 * WHEN IT DOES NOT: it described only the shape, so when the word cap was what failed the
 * correction retry got a rejection with no reason and answered "I cannot fix the error without
 * knowing what the rejection reason was" — which is not JSON, so the parse threw, on every run.
 * Every branch below quotes the offending line back.
 */
export function questionProblems(parsed: unknown): string[] {
  const problems: string[] = [];
  const d = parsed as Drafted | null;

  if (!d || typeof d !== "object" || !Array.isArray(d.questions)) {
    return ['the payload has no "questions" array at the top level'];
  }

  const bad = d.questions.filter(
    (q) => !q || typeof q.question !== "string" || !q.question.trim() || !SECTION_KEYS.has(q.section)
  );
  if (bad.length) {
    problems.push(
      `${bad.length} entr(y|ies) are not { section, question } with section one of ` +
        `${[...SECTION_KEYS].join(" | ")}: ${JSON.stringify(bad.slice(0, 3))}`
    );
    // Nothing below can be trusted about a malformed entry, so stop here rather than piling on.
    return problems;
  }

  if (d.questions.length !== TOTAL_QUESTIONS) {
    problems.push(
      `there are ${d.questions.length} questions and there must be exactly ${TOTAL_QUESTIONS}`
    );
  }

  const empty = CLOSER_SECTIONS.filter((s) => !d.questions.some((q) => q.section === s.key));
  if (empty.length) {
    problems.push(`these sections have no questions at all: ${empty.map((s) => s.key).join(", ")}`);
  }

  const long = d.questions.filter((q) => wordCount(q.question) > MAX_QUESTION_WORDS);
  if (long.length) {
    problems.push(
      `${long.length} question(s) run past ${MAX_QUESTION_WORDS} words and are read aloud on a ` +
        `phone, so they have to be shortened: ` +
        long
          .slice(0, 5)
          .map((q) => `[${wordCount(q.question)} words] "${q.question}"`)
          .join(" | ")
    );
  }

  // ‼️ A PRICE, A GUARANTEE OR A PROMISE OF CUSTOMERS FAILS THE GENERATION, not a warning above
  // it. These questions are read out loud to a client who is about to put a card on file, and
  // spokenPromises() is the same guard the delivery email and every phone script run through.
  for (const q of d.questions) {
    const hits = spokenPromises(q.question);
    if (hits.length) {
      problems.push(
        `"${q.question}" ${hits.map((h) => h.detail).join(" and ")}. This document may not ` +
          `promise customers, revenue, a return or a guarantee, and may not quote a price.`
      );
    }
  }

  return problems;
}

const SYSTEM = `You write the questions a consultant asks on a closing call.

You are given the ONLY facts that exist about this business. They were measured. Everything else
is unknown to you, and a number you did not receive is a number you may not write.

RULES, all of them absolute:
- Ask questions. Every entry ends in a question mark. Never a statement, never a script line.
- ${MAX_QUESTION_WORDS} words maximum per question. It is read aloud off a screen mid-call.
- Never quote a price, a fee, a discount or a package.
- Never promise customers, leads, revenue, growth, a return or a guarantee. Not even a hedged one.
- Never invent a figure, a competitor, a platform or a finding. If a fact is not in the block
  below, it does not exist. An absence stated in the block ("NONE", "NOT CHECKED") is a fact you
  may use, and it is never evidence of the opposite.
- No em dashes anywhere.
- The questions are for the OWNER to answer. Do not write questions we answer for ourselves.

The order is the CLOSER framework and it is the argument of the call:`;

function userPrompt(f: QuestionFacts): string {
  const sections = CLOSER_SECTIONS.map(
    (s) => `  ${s.key} (${s.letter} ${s.title}) - ${s.purpose}. Aim for about ${s.want}.`
  ).join("\n");

  return [
    `SECTIONS:\n${sections}`,
    "",
    `Write exactly ${TOTAL_QUESTIONS} questions in total, spread across all six sections. The`,
    "per-section numbers above are a target, not a quota: put a question where it belongs rather",
    "than padding a section, but every section must have at least one.",
    "",
    "Ground the specific ones in the facts. A question naming a real absent question of theirs,",
    "a real business named instead of them, or a real listing that disagrees is worth ten generic",
    "ones. Reinforce is where we show what has already been done and ask for the card.",
    "",
    "THE ONLY FACTS THAT EXIST:",
    factsBlock(f),
  ].join("\n");
}

/**
 * Draft the 33.
 *
 * ‼️ maxTokens STAYS UNDER 8000. claude-calls.ts retries a truncated response once at double the
 * budget, but only `if (requestedTokens < MAX_RETRY_TOKENS)` — passing the cap itself silently
 * disables the only recovery for truncation, and the cut-off response then fails as an
 * unparseable-JSON error whose message says nothing about length.
 */
export async function draftClosingQuestions(f: QuestionFacts): Promise<DraftedQuestion[]> {
  const result = await callClaudeJSON<Drafted>({
    model: "claude-sonnet-4-6",
    maxTokens: 4000,
    temperature: 0.4,
    system: SYSTEM,
    user: userPrompt(f),
    schemaHint: `{ "questions": [ { "section": "clarify|label|overview|sell|explain|reinforce", "question": string } ] }  // exactly ${TOTAL_QUESTIONS} entries`,
    validate: (parsed): parsed is Drafted => questionProblems(parsed).length === 0,
    describeInvalid: (parsed) => questionProblems(parsed).join(" ALSO: "),
  });

  // noDashes is the guarantee; the prompt line above it is only the request. Same belt the whole
  // outreach stack wears, and live runs confirm the model emits them anyway.
  return result.data.questions.map((q) => ({ section: q.section, question: noDashes(q.question) }));
}

