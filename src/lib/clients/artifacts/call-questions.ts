export interface QuestionFacts {
  clientName: string;
  city: string;
  vertical: string;
  /** audit_reports.score, or null when no baseline exists. Never computed here. */
  score: number | null;
  enginesRun: string[];
  /** Organic questions the business did not come back in. The money gap. */
  absentPrompts: string[];
  /** Organic questions it DID come back in. Named so nothing claims a total absence. */
  presentPrompts: string[];
  /** Prompts that were never measured. Not counted as an absence. */
  unmeasured: number;
  namedInstead: Array<{ name: string; timesNamed: number }>;
  confirmedCompetitors: string[];
  presence: {
    coreMismatch: string[];
    coreMissing: string[];
    coreNotChecked: string[];
    coreMatch: number;
    coreTotal: number;
  };
  reviews: {
    clientRecorded: Array<{ platform: string; count: number }>;
    competitorRecorded: Array<{ subject: string; platform: string; count: number }>;
    outstanding: number;
    total: number;
  };
  technical: {
    registrar: string | null;
    dnsProvider: string | null;
    cms: string | null;
    mailProvider: string | null;
    resolverHealthy: boolean;
    robotsBlocks: string[];
    siteSignals: string[];
  };
}

/**
 * Everything true about this client that a closing question may be built on.
 *
 * ‼️ ZERO MODEL CALLS AND ZERO DERIVED CLAIMS. Every field here is either a column or a count of
 * rows. `absentPrompts` is the only one that needed a decision, and it is the same one
 * findings.ts already makes: a prompt is absent when no engine named the business, and a prompt
 * that was never measured is neither absent nor present.
 */
export async function buildQuestionFacts(clientId: string): Promise<QuestionFacts | null> {
  const { data: client } = await supabaseAdmin
    .from("clients")
    .select(
      "legal_name, dba_name, website, domain, city, state, vertical_slug, business_type, site_intel"
    )
    .eq("id", clientId)
    .maybeSingle();

  if (!client) return null;

  const clientName = ((client.dba_name || client.legal_name) as string) ?? "";
  const aliases = buildAliases(clientName, (client.website as string | null) ?? (client.domain as string | null));

  const { data: report } = await supabaseAdmin
    .from("audit_reports")
    .select("id, score, engines, robots_check, site_signals")
    .eq("client_id", clientId)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  // ‼️ audit_runs.prompt, NOT audit_reports.prompts. See the file header.
  const { data: runRows } = report
    ? await supabaseAdmin
        .from("audit_runs")
        .select("prompt, engine, mentioned, recommended")
        .eq("report_id", report.id)
    : { data: null };

  const runs = (runRows ?? []).map((r) => ({
    prompt: r.prompt as string,
    engine: r.engine as string,
    mentioned: (r.mentioned as boolean | null) ?? null,
    recommended: (r.recommended as string[] | null) ?? [],
  }));

  // Collapse the engines: named when at least one engine named them, unmeasured only when no
  // engine produced an answer at all. The same rollup findings.ts prints on the page.
  const byPrompt = new Map<string, boolean | null>();
  for (const r of runs) {
    const current = byPrompt.get(r.prompt);
    if (r.mentioned === true) byPrompt.set(r.prompt, true);
    else if (current === undefined) byPrompt.set(r.prompt, r.mentioned);
  }

  const absentPrompts: string[] = [];
  const presentPrompts: string[] = [];
  let unmeasured = 0;
  for (const [prompt, mentioned] of byPrompt) {
    // A prompt that already names the business proves almost nothing, so it is not part of the
    // gap. Same 90/10 reasoning report-view.ts weights on.
    if (isMentioned(prompt, aliases)) continue;
    if (mentioned === null) unmeasured += 1;
    else if (mentioned) presentPrompts.push(prompt);
    else absentPrompts.push(prompt);
  }

  const sweep = await loadSweep(clientId);
  const core = sweep.filter((r) => r.tier === "core_six");
  const label = (key: string) => platformByKey(key)?.label ?? key;

  const reviewRows = await loadReviewAudit(clientId);
  const recorded = reviewRows.filter(isRecorded);

  const competitors = await selectedCompetitors(clientId);
  const intel = (client.site_intel as SiteIntel | null) ?? null;

  const robots =
    (report?.robots_check as Array<{ engine: string; role: string }> | null) ?? null;

  return {
    clientName,
    city: [client.city, client.state].filter(Boolean).join(", "),
    vertical: ((client.vertical_slug as string | null) || (client.business_type as string | null)) ?? "",
    score: (report?.score as number | null) ?? null,
    enginesRun: (report?.engines as string[] | null) ?? [],
    absentPrompts,
    presentPrompts,
    unmeasured,
    namedInstead: tallyRecommended(runs, aliases)
      .slice(0, 8)
      .map((t) => ({ name: t.name, timesNamed: t.timesNamed })),
    confirmedCompetitors: competitors.map((c) => c.name),
    presence: {
      coreMismatch: core.filter((r) => effectiveStatus(r) === "mismatch").map((r) => label(r.platform)),
      coreMissing: core.filter((r) => effectiveStatus(r) === "missing").map((r) => label(r.platform)),
      coreNotChecked: core.filter((r) => effectiveStatus(r) === "not_checked").map((r) => label(r.platform)),
      coreMatch: countByStatus(core).match,
      coreTotal: core.length,
    },
    reviews: {
      clientRecorded: recorded
        .filter((r) => r.subjectType === "client")
        .map((r) => ({ platform: r.platform, count: r.reviewCount ?? 0 })),
      competitorRecorded: recorded
        .filter((r) => r.subjectType === "competitor")
        .map((r) => ({ subject: r.subjectName, platform: r.platform, count: r.reviewCount ?? 0 })),
      outstanding: reviewRows.length - recorded.length,
      total: reviewRows.length,
    },
    technical: {
      registrar: intel?.registration.registrar ?? null,
      dnsProvider: intel?.dnsProvider ?? null,
      cms: intel?.cms ?? null,
      mailProvider: intel?.mailProvider ?? null,
      resolverHealthy: intel?.resolverHealthy ?? false,
      robotsBlocks: (robots ?? []).filter((r) => r.role === "search").map((r) => r.engine),
      siteSignals: ((report?.site_signals as Array<{ detail: string }> | null) ?? []).map((s) => s.detail),
    },
  };
}

/**
 * The facts, rendered for the prompt.
 *
 * ‼️ FRAMED AS "THE ONLY NUMBERS THAT EXIST", the same words the Call Coach's brief uses. Without
 * that framing a model rounds 10/100 into "under 15%" and supplies a competitor nobody measured.
 * An ABSENCE is stated out loud rather than left silent: absent beats forbidden, the rule this
 * repo applies to the price gate and to miniCheckContext.
 */
export function factsBlock(f: QuestionFacts): string {
  const lines: string[] = [];
  const say = (label: string, value: string) => lines.push(`${label}: ${value}`);

  say("BUSINESS", `${f.clientName}${f.city ? ` in ${f.city}` : ""}`);
  say("WHAT THEY ARE", f.vertical || "not recorded, so do not name a category");

  if (f.score === null) {
    say("SCORE", "NONE. No baseline exists. Do not cite a score, a percentage or a fraction.");
  } else {
    say("SCORE", `${f.score} out of 100, measured across ${f.enginesRun.length || 1} engine(s)`);
  }

  if (f.absentPrompts.length) {
    lines.push(
      `QUESTIONS THEY DID NOT COME BACK IN (${f.absentPrompts.length}), verbatim as run:`,
      ...f.absentPrompts.slice(0, 20).map((p) => `  - ${p}`)
    );
  } else {
    say("QUESTIONS THEY DID NOT COME BACK IN", "NONE recorded. Do not claim an absence.");
  }

  if (f.presentPrompts.length) {
    lines.push(
      `QUESTIONS THEY DID COME BACK IN (${f.presentPrompts.length}). Never say they are invisible:`,
      ...f.presentPrompts.slice(0, 8).map((p) => `  - ${p}`)
    );
  }
  if (f.unmeasured) {
    say("NEVER MEASURED", `${f.unmeasured} question(s). These are not absences and may not be counted as any.`);
  }

  if (f.namedInstead.length) {
    lines.push(
      "NAMED INSTEAD OF THEM, with the count each one actually earned:",
      ...f.namedInstead.map((c) => `  - ${c.name}, named in ${c.timesNamed}`)
    );
  } else {
    say("NAMED INSTEAD", "NONE. No competing business was named often enough to record.");
  }

  if (f.confirmedCompetitors.length) {
    say("COMPETITORS THEY CONFIRMED ON THE BOARD", f.confirmedCompetitors.join(", "));
  }

  const p = f.presence;
  say(
    "PRESENCE, CORE SIX",
    `${p.coreMatch} of ${p.coreTotal} match the canonical record` +
      (p.coreMismatch.length ? `; disagree: ${p.coreMismatch.join(", ")}` : "") +
      (p.coreMissing.length ? `; no listing: ${p.coreMissing.join(", ")}` : "") +
      (p.coreNotChecked.length
        ? `; NOT CHECKED (this is not a finding that they are correct): ${p.coreNotChecked.join(", ")}`
        : "")
  );

  const r = f.reviews;
  if (r.total === 0) {
    say("REVIEWS", "The review audit has not been seeded. No review number exists.");
  } else if (!r.clientRecorded.length && !r.competitorRecorded.length) {
    say("REVIEWS", `${r.total} rows, NONE read yet. Nobody has counted a review. Do not imply zero.`);
  } else {
    lines.push("REVIEWS, only what somebody actually counted:");
    for (const x of r.clientRecorded) lines.push(`  - them, ${x.platform}: ${x.count}`);
    for (const x of r.competitorRecorded) lines.push(`  - ${x.subject}, ${x.platform}: ${x.count}`);
    if (r.outstanding) lines.push(`  - ${r.outstanding} of ${r.total} rows are still unread and prove nothing`);
  }

  const t = f.technical;
  const tech = [
    t.registrar ? `domain registered with ${t.registrar}` : null,
    t.dnsProvider ? `DNS managed at ${t.dnsProvider}` : null,
    t.cms ? `site built on ${t.cms}` : null,
    t.mailProvider ? `email on ${t.mailProvider}` : null,
    t.robotsBlocks.length ? `robots.txt blocks ${t.robotsBlocks.join(", ")} by name` : null,
    ...t.siteSignals,
  ].filter(Boolean);
  say("TECHNICAL", tech.length ? tech.join("; ") : "nothing was measured about the site or its DNS");
  if (!t.resolverHealthy) {
    say("TECHNICAL CAVEAT", "the DNS lookup did not complete, so nothing about DNS may be asserted");
  }

  return lines.join("\n");
}

