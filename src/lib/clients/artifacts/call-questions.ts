/**
 * A ruled checkbox with the text beside it, so Matthew picks the ones he likes.
 *
 * ‼️ BUILT FROM kit PRIMITIVES RATHER THAN ADDED TO kit.ts. There is no checkbox in the kit and
 * this is the only document that wants one; kit.ts belongs to no lane and the presence and
 * cleanup PDFs are being edited in parallel, so a new export there is a merge conflict over
 * fourteen lines. It uses the kit's own margins, palette and paragraph layout, so it is not a
 * second PDF style — it is the kit's style with a square in front of it.
 */
function checkboxLine(state: PageState, text: string, opts?: { size?: number }): void {
  const size = opts?.size ?? 9.5;
  const box = 3.2;
  ensureSpace(state, size * 0.48 + 3);

  const top = state.y;
  setColor(state.doc, "draw", CARD_BORDER);
  state.doc.setLineWidth(0.3);
  state.doc.rect(MARGIN, top + 1.2, box, box, "S");

  paragraph(state, text, { size, x: MARGIN + box + 3, width: CONTENT_W - box - 3, gap: 1.6 });
}

/** The hard divider. Everything below it waits for the card. */
function divider(state: PageState, label: string): void {
  ensureSpace(state, 14);
  setColor(state.doc, "draw", RED);
  state.doc.setLineWidth(0.8);
  state.doc.line(MARGIN, state.y, PAGE_W - MARGIN, state.y);
  state.y += 5;
  paragraph(state, label, { bold: true, size: 12, color: RED });
}

