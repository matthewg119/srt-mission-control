//
// Matthew: "for step 20 ideally hand me a PDF with the questions we should be asking for this
// client based on the reports we did ... considering our closer framework we want to focus on
// clarify why they are here, label them with a problem, overview they're previous pain, sell
// them on the dream outcome, explain away they're concerns, and THEN, we reinforce they're
// decision by starting to show everything we did and after we collect payment asking questions
// about the funnel, online presence, GBP profile, capture DNS and all the rest, we cant capture
// all of this if they are not willing to put a card on file. Give me a list of 33 questions you
// would ask based on the report we did and I will select the ones I like."
//
// The call sheet is the sixty minutes. This is the CONVERSATION inside it: step 20 used to hand
// over a NAP read-aloud and a capture page and nothing to actually run the call with.
//
// ‼️ THE FACTS ARE CODE. THE QUESTIONS ARE THE MODEL'S. IT INVENTS NO NUMBER.
//
// Same split buildCoachNotes() makes in call-script.ts, and for the same reason stated there: a
// hallucinated figure in a document read aloud on a sales call is not one bad line, it is the
// whole call. buildQuestionFacts() assembles the score, the questions this business is absent
// from, who was named instead, the presence sweep, the review gaps and the site intelligence BY
// HAND, and they are handed over as "the only numbers that exist".
//
// ‼️ THIS IS THE FIRST ARTIFACT IN THIS FOLDER WITH A MODEL CALL IN IT, and that is not a
// precedent for the others. custom-question-set.ts states its own case at length: the tracked
// set has to be deterministic or the day-30 comparison compares two different measurements. This
// document is neither tracked nor measured — it is read once, by one person, on one call — so a
// model choosing the wording costs nothing that a re-run would break.
//
// ‼️ absent organic prompts COME FROM audit_runs.prompt, NEVER audit_reports.prompts.
// findings.ts states the hazard: that column is REGENERATED by every audit run, so quoting it
// would let a later scan rewrite the questions in a document already read out to a client.
