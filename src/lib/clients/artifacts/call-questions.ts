export function renderCallQuestions(d: CallQuestionsData): Buffer {
  const state = startDoc({
    title: `${d.clientName} — closing questions (internal)`,
    footer: plainFooter(
      "SRT internal · not for the client · every figure from this client's own reports"
    ),
  });

  coverHeading(state, {
    eyebrow: "Closing questions · internal",
    title: d.clientName,
    subtitle:
      "Pick the ones you want. Ordered by CLOSER, which is the same spine the live coach runs on.",
  });

  paragraph(
    state,
    d.facts.score === null
      ? "No baseline score exists for this client, so nothing below cites one."
      : `Built from this client's own reports: score ${d.facts.score} of 100, absent from ${d.facts.absentPrompts.length} of the questions their buyers ask, ${d.facts.namedInstead.length} businesses named instead.`,
    { color: MUTED, size: 9 }
  );

  for (const section of CLOSER_SECTIONS) {
    const list = d.questions.filter((q) => q.section === section.key);
    if (!list.length) continue;
    ensureSpace(state, 26);
    sectionHeading(state, `${section.letter} · ${section.title} — ${list.length}`);
    paragraph(state, section.purpose, { color: MUTED, size: 8.5 });
    for (const q of list) checkboxLine(state, q.question);
  }

  // ‼️ THE DIVIDER AND ITS OWN PAGE ARE THE WHOLE POINT OF THE SECOND HALF.
  // Matthew: "we cant capture all of this if they are not willing to put a card on file."
  // Nothing below is asked before the commitment, and putting it on the same page as the closing
  // questions is how it gets asked early.
  newPage(state);
  divider(state, "AFTER THE CARD");
  paragraph(
    state,
    "None of this is asked before the commitment. A client who has not committed does not hand over their Google account, and asking early is how a call ends with neither.",
    { bold: true, size: 10, color: AMBER }
  );
  paragraph(
    state,
    "Every value below is already on the record. Read them out; do not ask a question this document can answer.",
    { color: MUTED, size: 8.5 }
  );

  const blocks: Array<[string, string[]]> = [
    ["The funnel", d.after.funnel],
    ["Online presence and the GBP", d.after.presence],
    ["Search Console, Analytics and DNS", d.after.technical],
    ["The review workflow", d.after.reviews],
  ];

  for (const [title, items] of blocks) {
    if (!items.length) continue;
    ensureSpace(state, 24);
    sectionHeading(state, title);
    for (const item of items) checkboxLine(state, item, { size: 9 });
  }

  ensureSpace(state, 20);
  paragraph(state, "Anything they say here goes on the call sheet's capture page before you hang up.", {
    color: REEF,
    size: 9,
  });

  return finishDoc(state);
}

