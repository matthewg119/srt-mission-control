/**
 * Generate the closing questions and file them against step 20.
 *
 * Called from the `call_sheet` runner, so it runs when step 18 completes. It stores and records
 * and posts NOTHING — see the file header for why, and step-engine.ts's `call_held` card for
 * where it surfaces.
 */
export async function generateCallQuestions(clientId: string): Promise<AutoResult> {
  const facts = await buildQuestionFacts(clientId);
  if (!facts) return { ok: false, error: "client not found" };

  if (facts.score === null && !facts.absentPrompts.length) {
    // ‼️ REFUSES RATHER THAN WRITING GENERIC QUESTIONS. Matthew asked for questions "based on the
    // report we did", and with no report this would be thirty-three sales questions anybody could
    // have written, handed over in a document whose cover says they came from his own data.
    return {
      ok: false,
      error:
        "No baseline measurement for this client, so there is nothing to build closing questions " +
        "from. Confirm the baseline scan (step 2) first.",
    };
  }

  let questions: DraftedQuestion[];
  try {
    questions = await draftClosingQuestions(facts);
  } catch (e) {
    return { ok: false, error: `drafting the closing questions failed: ${(e as Error).message}` };
  }

  const { data: client } = await supabaseAdmin
    .from("clients")
    .select("domain, subdomain, booking_software, review_request_mode, review_owner_name")
    .eq("id", clientId)
    .maybeSingle();

  const domain = (client?.domain as string | null) ?? null;
  const { subdomainLabel } = await import("../normalize");
  const label = domain ? subdomainLabel((client?.subdomain as string | null) ?? "learn", domain) : null;

  const dnsRows = await loadDnsRows(clientId);
  const cname = dnsRows.find((r) => r.record_type === "CNAME");
  const txt = dnsRows.find((r) => r.record_type === "TXT");

  const after = buildAfterTheCard({
    facts,
    domain,
    hubHost: domain && label ? `${label}.${domain}` : null,
    reviewsHost: domain ? `reviews.${domain}` : null,
    // ‼️ THE SEEDED VALUE OR NOTHING. HUB_CNAME_TARGET's default is measured WRONG for this
    // project (Vercel issues per-domain targets), and a wrong value on a page somebody reads
    // down the phone is worse than a line saying it is not seeded yet.
    cnameTarget: (cname?.value as string | null) ?? null,
    searchConsoleTxt: (txt?.value as string | null) ?? null,
    bookingSoftware: (client?.booking_software as string | null) ?? null,
    reviewMode: (client?.review_request_mode as string | null) ?? null,
    reviewOwner: (client?.review_owner_name as string | null) ?? null,
  });

  let buffer: Buffer;
  try {
    buffer = renderCallQuestions({ clientName: facts.clientName, facts, questions, after });
  } catch (e) {
    return { ok: false, error: `render failed: ${(e as Error).message}` };
  }

  const stored = await storeGeneratedDoc({
    clientId,
    stepKey: "call_held",
    filename: `Closing questions (internal) - ${facts.clientName}.pdf`,
    buffer,
  });

  if (!stored.ok || !stored.docId) {
    return { ok: false, error: stored.error ?? "storing the closing questions failed" };
  }

  // The step's durable pointer to what it has waiting for it. Step 20's card reads this back
  // through outputRefsFor and links it; nothing is posted here.
  const { error } = await supabaseAdmin
    .from("client_delivery_steps")
    .update({ output_ref: stored.docId, updated_at: new Date().toISOString() })
    .eq("client_id", clientId)
    .eq("step_key", "call_held");

  if (error) {
    return { ok: false, error: `filing it against step 20 failed: ${error.message}` };
  }

  return {
    ok: true,
    docId: stored.docId,
    note: `${questions.length} closing questions filed against the call, waiting on step 20's card.`,
  };
}
