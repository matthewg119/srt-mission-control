// The findings report — delivery step 10, Runner v3 section 10, Artifact Templates section 2.
//
// This is the document the whole onboarding exists to produce. Six sections, in that order, no
// deviation. It is assembled from what steps 2 to 4c already wrote; it computes nothing new and
// invents nothing at all.
//
//   1 Where AI names other clinics in {city} instead of you
//   2 Why — presence and NAP
//   3 The review gap
//   4 The technical gap
//   5 The plan for the next 21 days
//   6 What we need from you
//
// ‼️ SECTION 5 IS A PLAN, NEVER A PRICED FIX LIST, AND FOR A PILOT NOTHING PURCHASABLE APPEARS
// IN IT AT ALL. Runner v3 section 10 and Artifact Templates section 2 both say it, and the
// pilot doc is the reason: these clinics are getting the service free so the case study measures
// the product. A price in this section turns a diagnostic into a pitch and makes every number
// above it look like a sales argument rather than a measurement.
//
// ‼️ VOCABULARY. named / not named / named alongside / named instead. Never ranked, position,
// #N or top result. The kit exports the four words so they are not retyped.
//
// ‼️ audit_runs.prompt IS THE QUESTION AS RUN AND IS THE ONLY THING QUOTED HERE.
// audit_reports.prompts is REGENERATED by every run, so quoting it would let a later audit
// silently rewrite the questions in a report already sent to a client.

