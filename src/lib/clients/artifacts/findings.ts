// 4 · The technical gap
// ─────────────────────────────────────────────────────────────────────────────

function sectionFour(
  state: PageState,
  args: { intel: SiteIntel | null; robots: unknown; signals: Array<{ kind: string; detail: string }> }
) {
  sectionHeading(state, "The technical gap", { number: 4 });
  paragraph(state, "One line each. No jargon.", { color: MUTED, size: 9 });

  const lines: string[] = [];

  if (args.intel) {
    const i = args.intel;
    if (i.resolverHealthy) {
      lines.push(
        i.dnsProvider
          ? `Your DNS is managed at ${i.dnsProvider}. That is where the three records go on the call.`
          : `Your DNS is on nameservers we do not recognise (${i.nameservers.join(", ") || "none found"}). We will read them to you rather than guess.`
      );
      if (i.mailProvider) lines.push(`Your email runs on ${i.mailProvider}.`);
    } else {
      lines.push("The DNS lookup did not complete, so nothing here is claimed about your DNS.");
    }

    if (i.registration.registrar) {
      lines.push(`Your domain is registered with ${i.registration.registrar}.`);
    }
    if (i.hosting.networkOrg || i.hosting.cdn) {
      lines.push(
        `Your website is hosted on ${i.hosting.networkOrg ?? "a network we could not identify"}${
          i.hosting.cdn ? `, served through ${i.hosting.cdn}` : ""
        }.`
      );
    }
    lines.push(
      i.cms
        ? `Your site is built on ${i.cms}.`
        : "We could not identify what your site is built on from its markup."
    );
  } else {
    lines.push("The site and hosting check has not run yet, so this section is incomplete.");
  }

  for (const s of args.signals) {
    lines.push(s.detail);
  }

  // The robots finding is the one with real teeth: a site that blocks the AI crawlers by name
  // cannot be quoted by them no matter what else is fixed.
  const robots = args.robots as Array<{ bot: string; engine: string; role: string }> | null;
  if (robots === null) {
    lines.push("We could not read your robots.txt, so nothing is claimed about crawler access.");
  } else if (robots.length === 0) {
    lines.push("Your robots.txt does not block the AI crawlers.");
  } else {
    const searchBots = robots.filter((r) => r.role === "search");
    if (searchBots.length) {
      lines.push(
        `Your site blocks ${searchBots.map((r) => r.engine).join(", ")} by name. Those assistants cannot read your pages at all.`
      );
    }
  }

  bulletList(state, lines);
}

