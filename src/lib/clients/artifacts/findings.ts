// 1 · Where AI names other clinics instead of you
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ‼️ HOW THE HEADLINE ROLLS UP, STATED BECAUSE RUNNER V3 SECTION 4 ASKED TO BE TOLD.
 *
 * Artifact Templates section 3 does not define how several engines collapse into one
 * "named in X of 20". Section 4 says: if it does not, define it as "named by at least one
 * engine", always print the per-engine grid underneath, and say you had to define it. That is
 * what this does, and the definition is printed on the page rather than left in code.
 *
 * A question with `mentioned === null` was never measured and is NOT counted as "not named".
 * Those are different claims: one is about what an engine said, the other about what we ran.
 */
function namedCount(runs: RunRow[]): { named: number; measured: number; unmeasured: number } {
  const byPrompt = new Map<string, boolean | null>();
  for (const r of runs) {
    const current = byPrompt.get(r.prompt);
    if (r.mentioned === true) byPrompt.set(r.prompt, true);
    else if (current === undefined) byPrompt.set(r.prompt, r.mentioned);
  }
  let named = 0;
  let unmeasured = 0;
  for (const v of byPrompt.values()) {
    if (v === true) named += 1;
    else if (v === null) unmeasured += 1;
  }
  return { named, measured: byPrompt.size - unmeasured, unmeasured };
}

function perEngineGrid(runs: RunRow[]): TableRow[] {
  const byEngine = new Map<string, { named: number; total: number }>();
  for (const r of runs) {
    if (r.mentioned === null) continue;
    const e = byEngine.get(r.engine) ?? { named: 0, total: 0 };
    e.total += 1;
    if (r.mentioned) e.named += 1;
    byEngine.set(r.engine, e);
  }
  return [...byEngine.entries()].map(([engine, v]) => ({
    label: ENGINE_LABEL[engine] ?? engine,
    value: `named in ${v.named} of ${v.total}`,
    tone: v.named === 0 ? "bad" : v.named < v.total / 2 ? "warn" : "good",
  }));
}

async function screenshotBytes(docId: string): Promise<Buffer | null> {
  try {
    const url = await signedDocUrl(docId);
    if (!url) return null;
    const res = await fetch(url);
    if (!res.ok) return null;
    return Buffer.from(await res.arrayBuffer());
  } catch {
    return null;
  }
}

async function sectionOne(
  state: PageState,
  args: { city: string; clientName: string; runs: RunRow[]; aliases: string[]; screenshotIds: string[] }
) {
  sectionHeading(state, `Where AI names other clinics in ${args.city} instead of you`, { number: 1 });

  const { named, measured, unmeasured } = namedCount(args.runs);
  const total = measured + unmeasured;

  paragraph(
    state,
    `When somebody in ${args.city} asks an AI assistant the kinds of questions your patients ask, you are named in ${named} of ${total}.`,
    { bold: true, size: 12, color: named === 0 ? RED : AMBER }
  );

  if (unmeasured > 0) {
    paragraph(
      state,
      `${unmeasured} of those ${total} could not be measured and are not counted either way.`,
      { color: MUTED, size: 9 }
    );
  }

  paragraph(
    state,
    'Counted as named when at least one engine named you. The per-engine breakdown is below, so you can see exactly where that count comes from.',
    { color: MUTED, size: 8.5 }
  );

  keyValueTable(state, perEngineGrid(args.runs), { labelWidth: 60 });

  // Screenshots of the real answers. Printed before the tally, because a client believes a
  // screenshot of their own question being answered with somebody else's name in a way no
  // number achieves.
  for (const id of args.screenshotIds.slice(0, 5)) {
    image(state, await screenshotBytes(id), {
      maxH: 85,
      caption: "The answer as it appeared, unedited.",
      fallbackLabel: "Screenshot on file",
    });
  }

  const tallies = tallyRecommended(args.runs, args.aliases);
  if (tallies.length) {
    paragraph(state, `Who was ${NAMED_INSTEAD}`, { bold: true, size: 10.5 });
    keyValueTable(
      state,
      tallies.slice(0, 8).map((t) => ({
        label: t.name,
        value: `named in ${t.timesNamed} of ${total}`,
        tone: "warn" as const,
      })),
      { labelWidth: 80 }
    );
    paragraph(
      state,
      "These are the businesses an assistant puts in front of somebody who never typed a business name at all.",
      { color: MUTED, size: 9 }
    );
  } else {
    paragraph(state, "No competing business was named consistently enough to list.", { color: MUTED });
  }
}

