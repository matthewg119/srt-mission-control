function sectionTwo(
  state: PageState,
  args: { canonical: Canonical; rows: Awaited<ReturnType<typeof loadSweep>>; presenceDocUrl: string | null }
) {
  sectionHeading(state, "Why", { number: 2 });

  const core = args.rows.filter((r) => r.tier === "core_six");
  const coreCounts = countByStatus(core);

  const variants = new Set(
    args.rows
      .filter((r) => r.rawAddress)
      .map((r) => (r.rawAddress ?? "").toLowerCase().replace(/\s+/g, " ").trim())
  );

  if (variants.size > 1) {
    paragraph(
      state,
      `Your address appears ${variants.size} different ways across the platforms we checked. An assistant trying to confirm who you are finds several answers and trusts none of them.`,
      { size: 10.5, bold: true }
    );
  } else {
    paragraph(
      state,
      "An assistant confirms a business by finding the same name, address and phone in several independent places. Where those records disagree, it cannot confirm you exist as one business.",
      { size: 10 }
    );
  }

  paragraph(state, "The core six — the records the engines lean on hardest", { bold: true, size: 10 });
  keyValueTable(
    state,
    core.map((r) => {
      const status = effectiveStatus(r);
      return {
        label: platformByKey(r.platform)?.label ?? r.platform,
        value:
          status === "match"
            ? "matches your record"
            : status === "mismatch"
              ? `does not match: ${r.rawAddress ?? r.rawPhone ?? r.rawName ?? "see report"}`
              : status === "duplicate"
                ? "more than one live listing"
                : status === "missing"
                  ? "no listing found"
                  : "not checked",
        tone:
          status === "match" ? ("good" as const) : status === "not_checked" ? ("normal" as const) : ("warn" as const),
      };
    }),
    { labelWidth: 60 }
  );

  // ‼️ Never "no issues found". If it was not checked, the document says it was not checked.
  if (coreCounts.not_checked) {
    paragraph(
      state,
      `${coreCounts.not_checked} of the core six have not been checked yet. That is not a finding that they are correct.`,
      { color: AMBER, bold: true, size: 9.5 }
    );
  }

  const extendedCounts = countByStatus(args.rows.filter((r) => r.tier === "extended"));
  paragraph(
    state,
    `Twelve smaller directories were also reviewed for context: ${extendedCounts.match} match, ${extendedCounts.mismatch} do not, ${extendedCounts.missing} have no listing, ${extendedCounts.not_checked} not checked. These matter less and are not part of the first three weeks of work.`,
    { color: MUTED, size: 9 }
  );

  if (args.presenceDocUrl) {
    paragraph(state, `The full record, platform by platform, with screenshots: ${args.presenceDocUrl}`, {
      color: REEF,
      size: 9,
    });
  }

}

