interface RunRow {
  prompt: string;
  engine: string;
  mentioned: boolean | null;
  recommended: string[];
}

const ENGINE_LABEL: Record<string, string> = {
  openai: "ChatGPT",
  chatgpt_web: "ChatGPT",
  perplexity: "Perplexity",
  gemini: "Gemini",
};

