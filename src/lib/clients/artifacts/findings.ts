export async function generateFindings(
  clientId: string
): Promise<{ ok: boolean; error?: string; docId?: string }> {
  const { data: client } = await supabaseAdmin
    .from("clients")
    .select("id, legal_name, dba_name, city, state, domain, website, site_intel")
    .eq("id", clientId)
    .maybeSingle();

  if (!client) return { ok: false, error: "client not found" };

  const canonical = await canonicalFor(clientId);
  if (!canonical) return { ok: false, error: "no canonical record" };

  const { data: report } = await supabaseAdmin
    .from("audit_reports")
    .select("id, engines, robots_check, site_signals")
    .eq("client_id", clientId)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  if (!report) {
    return { ok: false, error: "no baseline run for this client, so section 1 has nothing to report" };
  }

  const { data: runRows } = await supabaseAdmin
    .from("audit_runs")
    .select("prompt, engine, mentioned, recommended")
    .eq("report_id", report.id);

  const runs: RunRow[] = (runRows ?? []).map((r) => ({
    prompt: r.prompt as string,
    engine: r.engine as string,
    mentioned: (r.mentioned as boolean | null) ?? null,
    recommended: (r.recommended as string[] | null) ?? [],
  }));

  const rows = await loadSweep(clientId);
  const competitors = await selectedCompetitors(clientId);
  const reviewRows = await loadReviewAudit(clientId);

  // Screenshots filed against the baseline step are section 1's evidence.
  const { data: shots } = await supabaseAdmin
    .from("client_docs")
    .select("id, content_type")
    .eq("client_id", clientId)
    .eq("delivery_step_key", "baseline_scan")
    .eq("source", "slack")
    .limit(5);

  const { data: presenceDoc } = await supabaseAdmin
    .from("client_docs")
    .select("id")
    .eq("client_id", clientId)
    .eq("delivery_step_key", "presence_pdf")
    .eq("source", "generated")
    .order("uploaded_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  const { data: versions } = await supabaseAdmin
    .from("question_set_versions")
    .select("version")
    .eq("vertical", "med_spa");

  const clientName = ((client.dba_name || client.legal_name) as string) ?? "";
  const city = [client.city, client.state].filter(Boolean).join(", ") || "your area";
  const appBase = process.env.NEXT_PUBLIC_APP_URL || "https://mission.srtagency.com";

  const state = startDoc({
    title: `${clientName} — findings`,
    footer: fidelityFooter({
      questions: new Set(runs.map((r) => r.prompt)).size,
      engines: ((report.engines as string[] | null) ?? ["chatgpt_web"]),
      date: new Date(),
      questionSetVersions: (versions ?? []).map((v) => v.version as string),
    }),
  });

  coverHeading(state, {
    eyebrow: "Findings",
    title: clientName,
    subtitle: `What AI assistants currently say when somebody in ${city} asks for a clinic like yours, and why.`,
  });

  await sectionOne(state, {
    city,
    clientName,
    runs,
    aliases: [client.legal_name as string, client.dba_name as string].filter(Boolean),
    screenshotIds: (shots ?? []).map((s) => s.id as string),
  });

  sectionTwo(state, {
    canonical,
    rows,
    presenceDocUrl: presenceDoc ? `${appBase}/api/clients/${clientId}/docs/${presenceDoc.id}` : null,
  });

  sectionThree(state, { clientName, competitors, reviewRows });

  sectionFour(state, {
    intel: (client.site_intel as SiteIntel | null) ?? null,
    robots: report.robots_check,
    signals: ((report.site_signals as Array<{ kind: string; detail: string }> | null) ?? []),
  });

  sectionFive(state, {
    clientName,
    hasCoreIssues: rows.some(
      (r) => r.tier === "core_six" && ["mismatch", "duplicate", "missing"].includes(effectiveStatus(r))
    ),
  });

  sectionSix(state, {
    intel: (client.site_intel as SiteIntel | null) ?? null,
    domain: (client.domain as string) ?? "",
  });

  const buffer = finishDoc(state);

  const { named, measured, unmeasured } = namedCount(runs);
  const notChecked = countByStatus(rows).not_checked;

  const message = [
    `:page_facing_up: Findings for *${clientName}*. Named in ${named} of ${measured + unmeasured}.`,
    notChecked ? `:warning: ${notChecked} platforms are still "not checked" and the PDF says so.` : "",
    competitors.length === 0 ? ":warning: No competitors selected, so section 3 is a placeholder." : "",
    `Fidelity: ${((report.engines as string[] | null) ?? ["chatgpt_web"]).length} engine. Read it before it goes anywhere near the client.`,
  ]
    .filter(Boolean)
    .join("\n");

  const result = await deliverArtifact({
    clientId,
    stepKey: "findings_doc",
    filename: `Findings - ${clientName}.pdf`,
    buffer,
    message,
  });

  return { ok: result.ok, error: result.error, docId: result.docId };
}
